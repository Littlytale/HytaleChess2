public class ExampleCommand extends AbstractPlayerCommand {

    public ExampleCommand(String name, String description) {
        super(name, description);
    }

    @Override
    protected void execute(@Nonnull CommandContext commandContext, @Nonnull Store<EntityStore> store, @Nonnull Ref<EntityStore> ref, @Nonnull PlayerRef playerRef, @Nonnull World world) {
        Ref<EntityStore> prefabPreviewRef = PersistentPrefabPreview.spawn(store, new Vector3d(store.getComponent(ref, TransformComponent.getComponentType()).getPosition()), new Rotation3f(), "Cave/Hive/Poisoned/Hive_Poisoned_001", Integer.MAX_VALUE);

        commandContext.sendMessage(Message.raw("Sollte funktioniert haben!"));
    }
}
